use crate::model::FormatCategory;

#[derive(Debug, Clone, Copy)]
pub struct FormatSpec {
    pub ext: &'static str,
    pub name: &'static str,
    pub category: FormatCategory,
    pub mime: &'static str,
    pub language: Option<&'static str>,
}

#[derive(Debug, Clone, Copy)]
pub struct AmbiguousSpec {
    pub ext: &'static str,
    pub candidates: &'static [&'static str],
}

macro_rules! fmt {
    ($ext:expr, $name:expr, $cat:expr, $mime:expr) => {
        FormatSpec { ext: $ext, name: $name, category: $cat, mime: $mime, language: None }
    };
    ($ext:expr, $name:expr, $cat:expr, $mime:expr, $lang:expr) => {
        FormatSpec { ext: $ext, name: $name, category: $cat, mime: $mime, language: Some($lang) }
    };
}

