pub fn lookup_extension(file_name: &str) -> (Option<String>, Option<&'static FormatSpec>) {
    let lower = file_name.trim().to_ascii_lowercase();
    for (name, spec_name, cat, mime, lang) in SPECIAL_FILENAMES {
        if lower == *name {
            // Return static FormatSpec via lookup in FORMAT_REGISTRY if present or direct match
            let clean = name.trim_start_matches('.');
            if let Some(found) = FORMAT_REGISTRY.iter().find(|f| f.ext == clean) {
                return (Some(clean.to_string()), Some(found));
            }
            // Fallback static match
            let _ = (spec_name, cat, mime, lang);
        }
    }

    // Multi-part compound extensions first (.tar.gz, .tar.xz, .tar.bz2, .tar.zst, .gradle.kts, .pnpm-lock.yaml, .yarn.lock)
    for compound in [
        "tar.gz",
        "tar.bz2",
        "tar.xz",
        "tar.zst",
        "gradle.kts",
        "pnpm-lock.yaml",
        "yarn.lock",
        "sublime-project",
        "sublime-workspace",
        "code-workspace",
        "node-version",
    ] {
        let suffix = format!(".{compound}");
        if lower.ends_with(&suffix) {
            if let Some(found) = FORMAT_REGISTRY.iter().find(|f| f.ext == compound) {
                return (Some(compound.to_string()), Some(found));
            }
        }
    }

    if let Some(dot) = lower.rfind('.') {
        if dot + 1 < lower.len() {
            let ext = &lower[dot + 1..];
            let found = FORMAT_REGISTRY.iter().find(|f| f.ext == ext);
            return (Some(ext.to_string()), found);
        }
    }
    (None, None)
}

pub fn lookup_special_filename(file_name: &str) -> Option<&'static (&'static str, &'static str, FormatCategory, &'static str, &'static str)> {
    let lower = file_name.trim().to_ascii_lowercase();
    SPECIAL_FILENAMES.iter().find(|(n, _, _, _, _)| *n == lower)
}

pub fn lookup_ambiguity(ext: &str) -> Option<&'static AmbiguousSpec> {
    AMBIGUOUS_EXTENSIONS.iter().find(|a| a.ext.eq_ignore_ascii_case(ext))
}
